"""Protocol Buffers over ZeroMQ.

The schema lives in proto/sensor.proto and is compiled once:
    pip install protobuf grpcio-tools
    python -m grpc_tools.protoc -I proto --python_out=proto proto/sensor.proto
Both sides (Python, C++, Java, ...) generate code from the same file, so the
message layout is versioned and type-safe - unlike hand-made struct layouts.
Run:  python k05_protobuf.py
"""

import sys
from pathlib import Path

import zmq

sys.path.insert(0, str(Path(__file__).parent / "proto"))
import sensor_pb2  # noqa: E402  (generated by protoc)

ctx = zmq.Context()
pub = ctx.socket(zmq.PAIR)
sub = ctx.socket(zmq.PAIR)
pub.bind("inproc://proto")
sub.connect("inproc://proto")

reading = sensor_pb2.SensorReading(sensor_id=17, timestamp=1792842244.44,
                                   temperature=21.53, humidity=48.2, battery=0.87,
                                   room="livingroom")
raw = reading.SerializeToString()
pub.send_multipart([b"sensor.livingroom", raw])

topic, data = sub.recv_multipart()
received = sensor_pb2.SensorReading()
received.ParseFromString(data)
print(f"{topic.decode()}: {len(data)} bytes -> room={received.room}, "
      f"temperature={received.temperature:.2f}, battery={received.battery:.2f}")

pub.close()
sub.close()
ctx.term()
